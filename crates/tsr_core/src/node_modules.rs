/// Exact membership of `ExclusivelyPrefixedNodeCoreModules` at the source pin.
pub fn exclusively_prefixed_node_core_module(name: &[u8]) -> bool {
    matches!(
        name,
        b"node:quic" | b"node:sea" | b"node:sqlite" | b"node:test" | b"node:test/reporters"
    )
}

/// Membership of `NodeCoreModules()`: every unprefixed name with and without
/// `node:`, and the exclusively prefixed names.
pub fn node_core_module(name: &[u8]) -> bool {
    unprefixed_node_core_module(name)
        || name
            .strip_prefix(b"node:")
            .is_some_and(unprefixed_node_core_module)
        || exclusively_prefixed_node_core_module(name)
}

/// port: tsc/internal/core/nodemodules.go:NonRelativeModuleNameForTypingCache
pub fn non_relative_module_name_for_typing_cache(module_name: &[u8]) -> &[u8] {
    if node_core_module(module_name) {
        return b"node";
    }
    module_name
}
