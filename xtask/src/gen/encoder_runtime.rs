//! Runtime codecs consume resolver facts; no schema parsing or type inference.
use super::{validate, Export, Node};
use crate::gen::ast::{array, children, rust_type, snake, string};
use serde_json::Value;
use std::{collections::BTreeMap, path::PathBuf};

fn pattern(kinds: &[&str]) -> String {
    let alternatives = kinds
        .iter()
        .map(|kind| format!("SyntaxKind::{kind}"))
        .collect::<Vec<_>>()
        .join(" | ");
    format!("Some({alternatives})")
}
fn getter(node: &Node) -> String {
    format!(
        "node.data_source().as_{}().expect(\"{} payload required by Go kind dispatch\")",
        snake(&node.name),
        node.name
    )
}
fn member<'a>(ast: &'a Value, name: &str) -> Result<&'a Value, String> {
    array(ast, "members")?
        .iter()
        .find(|m| {
            m["name"]
                .as_str()
                .is_some_and(|actual| actual.eq_ignore_ascii_case(name))
        })
        .ok_or_else(|| format!("encoder missing AST member {}.{name}", ast["name"]))
}
fn or_expression(bits: &[String]) -> String {
    if bits.len() == 1 && bits[0].starts_with('(') && bits[0].ends_with(')') {
        bits[0][1..bits[0].len() - 1].into()
    } else {
        bits.join(" | ")
    }
}
fn common_decode(node: &Node, output: &mut String) {
    for field in &node.common_data {
        let name = snake(&field.name);
        let shift = field.bit_position;
        let mask = (1u32 << field.bit_width) - 1;
        if field.kinds.is_empty() {
            output.push_str(&format!("let {name} = common & {} != 0;\n", 1u32 << shift));
        } else {
            let base = usize::from(field.optional);
            let index_expression = if shift == 0 {
                "common".into()
            } else {
                format!("(common >> {shift})")
            };
            output.push_str(&format!(
                "let {name} = match {index_expression} & {mask} {{\n"
            ));
            for (index, kind) in field.kinds.iter().enumerate() {
                output.push_str(&format!("{} => SyntaxKind::{kind}.into(),\n", index + base));
            }
            output.push_str("_ => NodeKind::default(),\n};\n");
        }
    }
}
fn defaults(field: &Value) -> Result<String, String> {
    Ok(match rust_type(&field["type"])?.as_str() {
        "NodeId" | "NodeListId" => "None".into(),
        "bool" => "false".into(),
        "i32" | "u32" => "0".into(),
        "NodeKind" => "NodeKind::default()".into(),
        "NodeSlice" => "tsr_ast::NodeSlice::empty()".into(),
        "JsString" => "tsr_ast::JsString::default()".into(),
        "TextSlice" => "tsr_ast::TextSlice::empty()".into(),
        other => return Err(format!("encoder unsupported factory default {other}")),
    })
}

pub(super) fn emit(
    ast: &Value,
    encoder: &Value,
    pin: &str,
) -> Result<BTreeMap<PathBuf, String>, String> {
    let export: Export = serde_json::from_value(encoder.clone()).map_err(|e| e.to_string())?;
    let owners = validate(&export)?;
    let ast_nodes: BTreeMap<_, _> = array(ast, "nodes")?
        .iter()
        .map(|n| Ok((string(n, "name")?, n)))
        .collect::<Result<_, String>>()?;
    let mut out=format!("// Generated by cargo xtask gen; do not edit.\n// Upstream: {pin}\n// upstream: tsc/internal/api/encoder/encoder_generated.go\n// upstream: tsc/internal/api/encoder/decoder_generated.go\nuse tsr_ast::{{AstView,NodeAccess,NodeId,NodeKind,FactoryMethods,SyntaxKind}};\nuse crate::{{DataType,walk::Edge,string_table::StringTable,decoder::Decoder}};\n");
    out.push_str("// upstream: tsc/internal/api/encoder/encoder_generated.go:getNodeDataType\npub(crate) fn data_type(kind:NodeKind)->DataType { match kind.known(){\n");
    for category in ["string", "extended"] {
        let kinds = owners
            .iter()
            .filter_map(|(kind, index)| {
                (export.nodes[*index].data_type == category).then_some(*kind)
            })
            .collect::<Vec<_>>();
        if !kinds.is_empty() {
            out.push_str(&format!(
                "{} => DataType::{},\n",
                pattern(&kinds),
                if category == "string" {
                    "String"
                } else {
                    "Extended"
                }
            ));
        }
    }
    out.push_str("_=>DataType::Children,}}\n");
    out.push_str("// upstream: tsc/internal/api/encoder/encoder_generated.go:getNodeCommonData\n// port: tsc/internal/api/encoder/encoder.go:boolToByte\n// boolToByte is represented by u32::from(bool), preserving its exact 0/1 values.\npub(crate) fn common_data(node:&(impl NodeAccess+?Sized))->u32 { match node.kind().known(){\n");
    for node in &export.nodes {
        if node.hand_written_common_data {
            if node.data_type == "children" {
                if node.name != "SyntheticExpression" {
                    return Err(format!(
                        "unimplemented custom common-data codec {}",
                        node.name
                    ));
                }
                out.push_str("// port: tsc/internal/api/encoder/encoder.go:getNodeCommonData_SyntheticExpression\nSome(SyntaxKind::SyntheticExpression)=>panic!(\"SyntheticExpression should never be encoded\"),\n");
            }
            continue;
        }
        if node.common_data.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "{}=>{{let n={};\n",
            pattern(&node.kinds.iter().map(String::as_str).collect::<Vec<_>>()),
            getter(node)
        ));
        let mut bits = Vec::new();
        for field in &node.common_data {
            let name = snake(&field.name);
            if field.kinds.is_empty() {
                bits.push(format!(
                    "(u32::from(n.{name}()) << {})",
                    24 + field.bit_position
                ));
            } else {
                out.push_str(&format!("let {name}=match n.{name}().known() {{"));
                for (index, kind) in field.kinds.iter().enumerate() {
                    if index == 0 && !field.optional {
                        continue;
                    }
                    out.push_str(&format!(
                        "Some(SyntaxKind::{kind})=>{}u32,",
                        index + usize::from(field.optional)
                    ));
                }
                out.push_str("_=>0,};\n");
                bits.push(format!("({name} << {})", 24 + field.bit_position));
            }
        }
        out.push_str(&format!("{} }},\n", or_expression(&bits)));
    }
    out.push_str("_=>0,}}\n");
    for mode in ["child_mask", "children"] {
        if mode == "child_mask" {
            out.push_str("// upstream: tsc/internal/api/encoder/encoder_generated.go:getChildrenPropertyMask\n// port: tsc/internal/api/encoder/encoder.go:hasModifiers\n// hasModifiers is the optional-list nonempty predicate used below.\n");
        }
        let signature = if mode == "child_mask" { "->u32" } else { "" };
        let extra = if mode == "child_mask" {
            ""
        } else {
            ", edges:&mut Vec<Edge>"
        };
        out.push_str(&format!("pub(crate) fn {mode}(view:AstView<'_>,node:&(impl NodeAccess+?Sized){extra}){signature} {{ match node.kind().known(){{\n"));
        for node in &export.nodes {
            let traversal = children(ast_nodes[&*node.name])?;
            if (mode == "child_mask" && node.children.is_empty())
                || (mode == "children" && traversal.is_empty())
            {
                continue;
            }
            out.push_str(&format!(
                "{}=>{{let n={};\n",
                pattern(&node.kinds.iter().map(String::as_str).collect::<Vec<_>>()),
                getter(node)
            ));
            if mode == "child_mask" {
                let bits=node.children.iter().enumerate().map(|(index,child)|{
                    let name=snake(string(member(ast_nodes[&*node.name],&child.name)?,"name")?);
                    let present=match child.child_type.as_str(){"modifierList"=>format!("n.{name}().is_some_and(|id| !view.list(id).expect(\"owned modifier list\").nodes().is_empty())"),"rawNodeList"=>format!("!n.{name}().is_empty()"),_=>format!("n.{name}().is_some()")};
                    Ok::<String,String>(if index==0 {format!("u32::from({present})")} else {format!("(u32::from({present}) << {index})")})
                }).collect::<Result<Vec<_>,_>>()?;
                out.push_str(&or_expression(&bits));
            } else {
                // The Go encoder walks NodeVisitor.VisitEachChild, whose Go-only
                // children include FullSignature even though the wire mask omits it.
                for child in traversal {
                    let name = snake(string(child, "name")?);
                    match rust_type(&child["type"])?.as_str() {
                        "NodeId" => out.push_str(&format!("if let Some(id)=n.{name}() {{edges.push(Edge::Node(id));}}\n")),
                        "NodeListId" if child["visit"] == "modifiers" => out.push_str(&format!("if let Some(id)=n.{name}() {{if !view.list(id).expect(\"owned modifier list\").nodes().is_empty() {{edges.push(Edge::List(id));}}}}\n")),
                        "NodeListId" => out.push_str(&format!("if let Some(id)=n.{name}() {{edges.push(Edge::List(id));}}\n")),
                        "NodeSlice" => out.push_str(&format!("edges.extend(view.node_slice(n.{name}()).expect(\"owned raw children\").iter().flatten().map(Edge::Node));\n")),
                        other => return Err(format!("unsupported encoder traversal child {other}")),
                    }
                }
            }
            out.push_str("},\n");
        }
        out.push_str(if mode == "child_mask" {
            "_=>0,}}\n"
        } else {
            "_=>{},}}\n"
        });
    }
    out.push_str("// upstream: tsc/internal/api/encoder/encoder_generated.go:recordNodeStrings\npub(crate) fn record_string(view:AstView<'_>,node:&(impl NodeAccess+?Sized),table:&mut StringTable<'_>)->u32 {match node.kind().known(){\n");
    for node in export.nodes.iter().filter(|n| n.data_type == "string") {
        let ast_node = ast_nodes[&*node.name];
        let name = node.text_member.as_ref().expect("validated string member");
        out.push_str(&format!(
            "{}=>{{let n={};\n",
            pattern(&node.kinds.iter().map(String::as_str).collect::<Vec<_>>()),
            getter(node)
        ));
        if rust_type(&member(ast_node, name)?["type"])? == "TextSlice" {
            out.push_str(&format!("let parts=view.text_slice(n.{}()).expect(\"owned text fragments\");let text:Vec<u8>=parts.iter().flat_map(|part|part.as_bytes().iter().copied()).collect();table.add(&text,node.kind(),node.pos(),node.end())",snake(name)));
        } else {
            out.push_str(&format!(
                "table.add(n.{}(),node.kind(),node.pos(),node.end())",
                snake(name)
            ));
        }
        out.push_str("},\n");
    }
    out.push_str("_=>panic!(\"unexpected string node kind {}\",node.kind()),}}\n");
    out.push_str("impl Decoder<'_> { pub(crate) fn create_generated(&mut self,kind:NodeKind,data:u32,child_indices:&[usize])->Result<NodeId,String>{let common=(data>>24)&0x3f;match data&0xc000_0000 {\n");
    for category in ["string", "children"] {
        out.push_str(if category == "string" {
            "// upstream: tsc/internal/api/encoder/decoder_generated.go:astDecoder.createStringNode\n"
        } else {
            "// upstream: tsc/internal/api/encoder/decoder_generated.go:astDecoder.createChildrenNode\n"
        });
        out.push_str(if category == "string" {
            "0x4000_0000=>{let text=self.get_string(data&0x00ff_ffff); match kind.known(){\n"
        } else {
            "_=>{match kind.known(){\n"
        });
        let mut decoder_owners: BTreeMap<&str, usize> = BTreeMap::new();
        for (index, node) in export
            .nodes
            .iter()
            .enumerate()
            .filter(|(_, n)| n.data_type == category)
        {
            for kind in &node.kinds {
                if decoder_owners
                    .get(kind.as_str())
                    .is_none_or(|old| export.nodes[*old].kinds.len() > node.kinds.len())
                {
                    decoder_owners.insert(kind, index);
                }
            }
        }
        for (index, node) in export
            .nodes
            .iter()
            .enumerate()
            .filter(|(_, n)| n.data_type == category)
        {
            let kinds = decoder_owners
                .iter()
                .filter_map(|(kind, owner)| (*owner == index).then_some(*kind))
                .collect::<Vec<_>>();
            if kinds.is_empty() {
                continue;
            }
            out.push_str(&format!("{}=>{{\n", pattern(&kinds)));
            if node.hand_written_common_data {
                out.push_str("// port: tsc/internal/api/encoder/decoder.go:decodeNodeCommonData_SyntheticExpression\npanic!(\"SyntheticExpression should never be decoded\")},\n");
                continue;
            }
            common_decode(node, &mut out);
            let mut args: BTreeMap<String, String> = node
                .common_data
                .iter()
                .map(|f| (snake(&f.name), snake(&f.name)))
                .collect();
            if category == "string" {
                let name = node.text_member.as_ref().expect("string member");
                if rust_type(&member(ast_nodes[&*node.name], name)?["type"])? == "TextSlice" {
                    out.push_str("let text=self.factory.text_slice(vec![text]).expect(\"decoded text owner\");\n");
                }
                args.insert(snake(name), "text".into());
            } else {
                if node.children.len() > 1 {
                    out.push_str("let mut cursor=0usize;\n");
                }
                for (ordinal, child) in node.children.iter().enumerate() {
                    let name = snake(string(
                        member(ast_nodes[&*node.name], &child.name)?,
                        "name",
                    )?);
                    let index = if node.children.len() == 1 {
                        if child.child_type == "node" {
                            out.push_str("// port: tsc/internal/api/encoder/decoder.go:astDecoder.singleChild\n");
                        } else if child.child_type == "nodeList" {
                            out.push_str("// port: tsc/internal/api/encoder/decoder.go:astDecoder.singleNodeListChild\n");
                        }
                        "child_indices.first().copied().unwrap_or(0)".into()
                    } else {
                        format!("Self::next_if(child_indices,&mut cursor,data as u8,{ordinal})")
                    };
                    let getter = match child.child_type.as_str() {
                        "node" => "node_at",
                        "nodeList" => "list_at",
                        "modifierList" => "modifier_at",
                        "rawNodeList" => {
                            if node.children.len() != 1 {
                                return Err("unexpected multi-property raw node list".into());
                            }
                            out.push_str(&format!(
                                "let {name}=self.generated_raw_list(child_indices);\n"
                            ));
                            args.insert(name.clone(), name);
                            continue;
                        }
                        _ => unreachable!(),
                    };
                    out.push_str(&format!("let {name}=self.{getter}({index});\n"));
                    args.insert(name.clone(), name);
                }
            }
            let ast_node = ast_nodes[&*node.name];
            let mut params = Vec::new();
            for field in array(ast_node, "members")?
                .iter()
                .filter(|m| m["noFactory"] == false)
            {
                let name = snake(string(field, "name")?);
                params.push(if field["kindParameter"] == true {
                    "kind".into()
                } else if let Some(value) = args.get(&name) {
                    value.clone()
                } else {
                    defaults(field)?
                });
            }
            // Alias kinds share a payload, but Go constructs their distinct
            // runtime kinds instead of the payload's default kind.
            for alias in array(ast_node, "kindAliases")? {
                let alias = alias.as_str().ok_or("encoder malformed factory alias")?;
                if kinds.contains(&alias) {
                    out.push_str(&format!(
                        "if kind == SyntaxKind::{alias} {{ return Ok(self.factory.new_{}({})); }}\n",
                        snake(alias),
                        params.join(",")
                    ));
                }
            }
            out.push_str(&format!(
                "Ok(self.factory.new_{}({}))}},\n",
                snake(&node.name),
                params.join(",")
            ));
        }
        out.push_str(if category=="string"{"_=>Err(format!(\"unknown string node kind {kind}\")),}},\n"}else{"_=>Err(format!(\"unhandled node kind {kind} with {} children\",child_indices.len())),}},\n"});
        if category == "string" {
            out.push_str("0x8000_0000=>self.create_extended(kind,data,child_indices),\n");
        }
    }
    out.push_str("}}}\n");
    Ok(BTreeMap::from([(
        PathBuf::from("crates/tsr_encoder/src/runtime_generated.rs"),
        out,
    )]))
}
