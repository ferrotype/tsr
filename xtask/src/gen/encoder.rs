//! Emit the pinned encoder generator's analyzed layouts without resolving schema types.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use serde::Deserialize;
use serde_json::Value;

#[path = "encoder_runtime.rs"]
mod runtime;

pub(super) fn emit_runtime(
    ast: &Value,
    encoder: &Value,
    pin: &str,
) -> Result<BTreeMap<PathBuf, String>, String> {
    runtime::emit(ast, encoder, pin)
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Export {
    version: u32,
    constants: BTreeMap<String, u32>,
    nodes: Vec<Node>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Node {
    name: String,
    kinds: Vec<String>,
    data_type: String,
    hand_written_common_data: bool,
    hand_written: bool,
    text_member: Option<String>,
    children: Vec<ChildField>,
    common_data: Vec<Field>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct ChildField {
    name: String,
    child_type: String,
    optional: bool,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Field {
    name: String,
    bit_position: u8,
    bit_width: u8,
    optional: bool,
    kinds: Vec<String>,
}

const CONSTANTS: &[(&str, &str)] = &[
    ("ProtocolVersion", "PROTOCOL_VERSION"),
    ("NodeOffsetKind", "NODE_OFFSET_KIND"),
    ("NodeOffsetPos", "NODE_OFFSET_POS"),
    ("NodeOffsetEnd", "NODE_OFFSET_END"),
    ("NodeOffsetNext", "NODE_OFFSET_NEXT"),
    ("NodeOffsetParent", "NODE_OFFSET_PARENT"),
    ("NodeOffsetData", "NODE_OFFSET_DATA"),
    ("NodeOffsetFlags", "NODE_OFFSET_FLAGS"),
    ("NodeSize", "NODE_SIZE"),
    ("NodeDataTypeChildren", "NODE_DATA_TYPE_CHILDREN"),
    ("NodeDataTypeString", "NODE_DATA_TYPE_STRING"),
    ("NodeDataTypeExtendedData", "NODE_DATA_TYPE_EXTENDED_DATA"),
    ("NodeDataTypeMask", "NODE_DATA_TYPE_MASK"),
    ("NodeDataChildMask", "NODE_DATA_CHILD_MASK"),
    ("NodeDataStringIndexMask", "NODE_DATA_STRING_INDEX_MASK"),
    ("SyntaxKindNodeList", "SYNTAX_KIND_NODE_LIST"),
    ("HeaderOffsetMetadata", "HEADER_OFFSET_METADATA"),
    ("HeaderOffsetHashLo0", "HEADER_OFFSET_HASH_LO0"),
    ("HeaderOffsetHashLo1", "HEADER_OFFSET_HASH_LO1"),
    ("HeaderOffsetHashHi0", "HEADER_OFFSET_HASH_HI0"),
    ("HeaderOffsetHashHi1", "HEADER_OFFSET_HASH_HI1"),
    ("HeaderOffsetParseOptions", "HEADER_OFFSET_PARSE_OPTIONS"),
    ("HeaderOffsetStringOffsets", "HEADER_OFFSET_STRING_OFFSETS"),
    ("HeaderOffsetStringData", "HEADER_OFFSET_STRING_DATA"),
    ("HeaderOffsetExtendedData", "HEADER_OFFSET_EXTENDED_DATA"),
    (
        "HeaderOffsetStructuredData",
        "HEADER_OFFSET_STRUCTURED_DATA",
    ),
    ("HeaderOffsetNodes", "HEADER_OFFSET_NODES"),
    ("HeaderSize", "HEADER_SIZE"),
];

pub(super) fn emit(input: &Value, pin: &str) -> Result<BTreeMap<PathBuf, String>, String> {
    let export: Export = serde_json::from_value(input.clone())
        .map_err(|error| format!("invalid encoder export: {error}"))?;
    let owners = validate(&export)?;
    let mut output = format!(
        "//! upstream: tsc/internal/api/encoder/encoder_generated.go\n\
         //! upstream: tsc/internal/api/encoder/decoder_generated.go\n\
         //! port: tsc/internal/api/encoder/encoder.go\n\
         // Generated by cargo xtask gen from the pinned encoder analysis. DO NOT EDIT.\n\
         // Upstream: {pin}\n\
         use tsr_ast::SyntaxKind;\n\
         use crate::{{ChildProperty, ChildType, CommonDataField, DataType, NodeLayout}};\n\n"
    );
    for &(go_name, rust_name) in CONSTANTS {
        let value = export.constants[go_name];
        let literal = if value > 9999 {
            format!("0x{:04x}_{:04x}", value >> 16, value & 0xffff)
        } else {
            value.to_string()
        };
        output.push_str(&format!("pub const {rust_name}: u32 = {literal};\n"));
    }
    output.push_str("\npub static NODE_LAYOUTS: &[NodeLayout] = &[\n");
    for node in &export.nodes {
        let data_type = match node.data_type.as_str() {
            "children" => "Children",
            "string" => "String",
            "extended" => "Extended",
            _ => unreachable!("validated data type"),
        };
        output.push_str(&format!(
            "    NodeLayout {{ name: {:?}, kinds: {}, data_type: DataType::{data_type}, \
             hand_written_common_data: {}, text_member: {},\n        children: &[\n",
            node.name,
            kinds(&node.kinds),
            node.hand_written_common_data,
            node.text_member
                .as_ref()
                .map_or_else(|| "None".into(), |text| format!("Some({text:?})"))
        ));
        for child in &node.children {
            let child_type = match child.child_type.as_str() {
                "node" => "Node",
                "nodeList" => "NodeList",
                "rawNodeList" => "RawNodeList",
                "modifierList" => "ModifierList",
                _ => unreachable!("validated child type"),
            };
            output.push_str(&format!(
                "            ChildProperty {{ name: {:?}, child_type: ChildType::{child_type}, optional: {} }},\n",
                child.name, child.optional
            ));
        }
        output.push_str("        ], common_data: &[\n");
        for field in &node.common_data {
            output.push_str(&format!(
                "            CommonDataField {{ name: {:?}, bit_position: {}, bit_width: {}, \
                 optional: {}, kind_values: {} }},\n",
                field.name,
                field.bit_position,
                field.bit_width,
                field.optional,
                kinds(&field.kinds)
            ));
        }
        output.push_str("        ] },\n");
    }
    output.push_str(
        "];\n\n/// Every known kind has a pinned layout; this match verifies that coverage.\n\
                     pub fn layout(kind: SyntaxKind) -> &'static NodeLayout {\n    match kind {\n",
    );
    let mut node_kinds: BTreeMap<usize, Vec<String>> = BTreeMap::new();
    for (kind, index) in owners {
        node_kinds
            .entry(index)
            .or_default()
            .push(format!("SyntaxKind::{kind}"));
    }
    for (index, kinds) in node_kinds {
        output.push_str(&format!(
            "        {} => &NODE_LAYOUTS[{index}],\n",
            kinds.join(" | ")
        ));
    }
    output.push_str("    }\n}\n");
    Ok(BTreeMap::from([(
        PathBuf::from("crates/tsr_encoder/src/generated.rs"),
        output,
    )]))
}

fn kinds(values: &[String]) -> String {
    format!(
        "&[{}]",
        values
            .iter()
            .map(|kind| format!("SyntaxKind::{kind}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn valid_kind(name: &str) -> bool {
    let mut bytes = name.bytes();
    bytes.next().is_some_and(|first| first.is_ascii_uppercase())
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}

fn validate(export: &Export) -> Result<BTreeMap<&str, usize>, String> {
    if export.version != 1 || export.nodes.is_empty() {
        return Err("encoder export requires version 1 and nonempty nodes".into());
    }
    let expected: BTreeSet<_> = CONSTANTS.iter().map(|&(name, _)| name).collect();
    let actual: BTreeSet<_> = export.constants.keys().map(String::as_str).collect();
    if expected != actual {
        return Err("encoder wire constants do not match the exported inventory".into());
    }
    let mut names = BTreeSet::new();
    for node in &export.nodes {
        if !names.insert(&node.name) {
            return Err(format!("duplicate encoder node: {}", node.name));
        }
        if !matches!(node.data_type.as_str(), "children" | "string" | "extended") {
            return Err(format!("unknown encoder data type: {}", node.data_type));
        }
        if node.hand_written && node.data_type != "extended" {
            return Err(format!(
                "hand-written encoder node must use extended data: {}",
                node.name
            ));
        }
        if (node.data_type == "string") != node.text_member.is_some() {
            return Err(format!(
                "string encoder node requires exactly one text member: {}",
                node.name
            ));
        }
        let mut local_kinds = BTreeSet::new();
        for kind in &node.kinds {
            if !valid_kind(kind) || !local_kinds.insert(kind) {
                return Err(format!("invalid or duplicate encoder kind: {kind}"));
            }
        }
        let mut fields = BTreeSet::new();
        for child in &node.children {
            if child.name.is_empty() || !fields.insert(&child.name) {
                return Err(format!("empty or duplicate child field: {}", node.name));
            }
            if !matches!(
                child.child_type.as_str(),
                "node" | "nodeList" | "rawNodeList" | "modifierList"
            ) {
                return Err(format!("unknown child type: {}", child.child_type));
            }
        }
        let mut next_bit = 0;
        if node.hand_written_common_data && !node.common_data.is_empty() {
            return Err(format!(
                "custom common data also has automatic fields: {}",
                node.name
            ));
        }
        for field in &node.common_data {
            if field.name.is_empty() || !fields.insert(&field.name) {
                return Err(format!(
                    "empty or duplicate common-data field: {}",
                    node.name
                ));
            }
            let end = u16::from(field.bit_position) + u16::from(field.bit_width);
            if field.bit_position != next_bit || field.bit_width == 0 || end > 6 {
                return Err(format!(
                    "invalid common-data bit layout: {}.{}",
                    node.name, field.name
                ));
            }
            next_bit = end as u8;
            if field.kinds.iter().any(|kind| !valid_kind(kind)) {
                return Err(format!(
                    "invalid common-data kind: {}.{}",
                    node.name, field.name
                ));
            }
        }
    }
    // Match getNodeDataType's explicit string/extended cases and the specificity
    // rule in generateGoCreateChildrenNode. Token overlaps with specialized node
    // kinds; rejecting all overlap would discard valid pinned schema information.
    let mut owners: BTreeMap<&str, usize> = BTreeMap::new();
    for (index, node) in export.nodes.iter().enumerate() {
        for kind in &node.kinds {
            if let Some(&previous) = owners.get(kind.as_str()) {
                let existing = &export.nodes[previous];
                let replace = if node.data_type == existing.data_type {
                    if node.kinds.len() == existing.kinds.len() {
                        return Err(format!("ambiguous encoder kind owners: {kind}"));
                    }
                    node.kinds.len() < existing.kinds.len()
                } else if existing.data_type == "children" {
                    true
                } else if node.data_type == "children" {
                    false
                } else {
                    return Err(format!("conflicting encoder data types: {kind}"));
                };
                if replace {
                    owners.insert(kind, index);
                }
            } else {
                owners.insert(kind, index);
            }
        }
    }
    Ok(owners)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn input() -> Value {
        json!({"version":1,"constants":CONSTANTS.iter().map(|&(name,_)|(name,0)).collect::<BTreeMap<_,_>>(),
            "nodes":[{"name":"Example","kinds":["Identifier"],"dataType":"children",
                "handWrittenCommonData":false,"handWritten":false,"textMember":null,"children":[],
                "commonData":[{"name":"flag","bitPosition":0,"bitWidth":1,"optional":false,"kinds":[]}]}]})
    }

    #[test]
    fn rejects_colliding_kinds_and_unrecognized_encodings() {
        let mut value = input();
        let mut second = value["nodes"][0].clone();
        second["name"] = json!("Other");
        value["nodes"].as_array_mut().unwrap().push(second);
        assert!(emit(&value, "pin").is_err());
        value = input();
        value["nodes"][0]["dataType"] = json!("future");
        assert!(emit(&value, "pin").is_err());
        value = input();
        value["constants"]
            .as_object_mut()
            .unwrap()
            .remove("ProtocolVersion");
        assert!(emit(&value, "pin").is_err());
    }

    #[test]
    fn rejects_overflowing_overlapping_and_custom_automatic_bits() {
        for (position, width) in [(0, 7), (1, 1), (0, 0), (255, 255)] {
            let mut value = input();
            value["nodes"][0]["commonData"][0]["bitPosition"] = json!(position);
            value["nodes"][0]["commonData"][0]["bitWidth"] = json!(width);
            assert!(emit(&value, "pin").is_err());
        }
        let mut value = input();
        value["nodes"][0]["handWrittenCommonData"] = json!(true);
        assert!(emit(&value, "pin").is_err());
    }

    #[test]
    fn resolves_specific_child_nodes_and_explicit_string_data_over_token_fallback() {
        let mut value = input();
        value["nodes"][0]["kinds"] = json!(["Identifier", "PlusToken", "TrueKeyword"]);
        value["nodes"][0]["commonData"] = json!([]);
        let mut identifier = value["nodes"][0].clone();
        identifier["name"] = json!("Identifier");
        identifier["kinds"] = json!(["Identifier"]);
        identifier["dataType"] = json!("string");
        identifier["textMember"] = json!("text");
        let mut keyword = value["nodes"][0].clone();
        keyword["name"] = json!("KeywordExpression");
        keyword["kinds"] = json!(["TrueKeyword"]);
        value["nodes"]
            .as_array_mut()
            .unwrap()
            .extend([identifier, keyword]);
        let export: Export = serde_json::from_value(value).unwrap();
        let owners = validate(&export).unwrap();
        assert_eq!(owners["Identifier"], 1);
        assert_eq!(owners["PlusToken"], 0);
        assert_eq!(owners["TrueKeyword"], 2);
    }
}
