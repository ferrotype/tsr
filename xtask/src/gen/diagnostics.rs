//! Emit diagnostic data already normalized by the pinned Go generator.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use serde::Deserialize;
use serde_json::Value;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Export {
    version: u32,
    messages: Vec<Message>,
    #[serde(default)]
    locales: BTreeMap<String, BTreeMap<String, String>>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Message {
    name: String,
    key: String,
    text: String,
    code: i32,
    category: String,
    reports_unnecessary: bool,
    reports_deprecated: bool,
    elided_in_compatibility_pyramid: bool,
}

pub(super) fn emit(input: &Value, pin: &str) -> Result<BTreeMap<PathBuf, String>, String> {
    let export: Export = serde_json::from_value(input.clone())
        .map_err(|error| format!("invalid diagnostic export: {error}"))?;
    if export.version != 1 || export.messages.is_empty() {
        return Err("diagnostic export requires version 1 and nonempty messages".into());
    }
    let mut names = BTreeSet::new();
    let mut keys = BTreeMap::new();
    let mut previous = None;
    for (index, message) in export.messages.iter().enumerate() {
        if previous.is_some_and(|code| message.code <= code) {
            return Err(format!(
                "diagnostic codes must strictly increase: {}",
                message.code
            ));
        }
        previous = Some(message.code);
        if !valid_identifier(&message.name) || !names.insert(&message.name) {
            return Err(format!(
                "invalid or duplicate diagnostic name: {}",
                message.name
            ));
        }
        if message.key.is_empty() || keys.insert(&message.key, index).is_some() {
            return Err(format!(
                "empty or duplicate diagnostic key: {}",
                message.key
            ));
        }
        if !matches!(
            message.category.as_str(),
            "Warning" | "Error" | "Suggestion" | "Message"
        ) {
            return Err(format!("unknown diagnostic category: {}", message.category));
        }
    }

    let mut output = format!(
        "//! port: tsc/internal/diagnostics/diagnostics_generated.go\n\
         // Generated by cargo xtask gen from the pinned Go diagnostics exporter. DO NOT EDIT.\n\
         // Upstream: {pin}\n\
         // Names and localization keys come from convertPropertyName in generate.go.\n\
         #![allow(non_upper_case_globals)] // Preserve pinned diagnostic identifiers.\n\
         use crate::{{Category, Message}};\n\n\
         pub static MESSAGES: &[Message] = &[\n"
    );
    for message in &export.messages {
        output.push_str(&format!(
            "    Message {{ code: {}, category: Category::{}, key: {:?}, text: {:?}, \
             reports_unnecessary: {}, reports_deprecated: {}, elided_in_compatibility_pyramid: {} }},\n",
            number(message.code), message.category, message.key, message.text,
            message.reports_unnecessary, message.reports_deprecated,
            message.elided_in_compatibility_pyramid
        ));
    }
    output.push_str("];\n\n");
    for (index, message) in export.messages.iter().enumerate() {
        output.push_str(&format!(
            "pub const {}: &Message = &MESSAGES[{index}];\n",
            message.name
        ));
    }
    output.push_str("\npub(crate) static KEY_INDEX: &[(&str, usize)] = &[\n");
    for (key, index) in keys {
        output.push_str(&format!("    ({key:?}, {index}),\n"));
    }
    output.push_str("];\n");
    let mut files = BTreeMap::from([(
        PathBuf::from("crates/tsr_diagnostics/src/generated.rs"),
        output,
    )]);
    {
        const TAGS: [&str; 13] = [
            "zh-CN", "zh-TW", "cs-CZ", "de-DE", "es-ES", "fr-FR", "it-IT", "ja-JP", "ko-KR",
            "pl-PL", "pt-BR", "ru-RU", "tr-TR",
        ];
        if export.locales.len() != TAGS.len()
            || TAGS.iter().any(|tag| !export.locales.contains_key(*tag))
        {
            return Err("localization roster differs from pinned matcher".into());
        }
        let mut source=format!("// Generated by cargo xtask gen from pinned diagnostics localization assets.\n// Upstream: {pin}\npub(crate) static TABLE_JSON: &[&str] = &[\n");
        for tag in TAGS {
            let values = &export.locales[tag];
            if values.is_empty() {
                return Err(format!("empty localization table: {tag}"));
            }
            let json = serde_json::to_string(values).map_err(|error| error.to_string())?;
            source.push_str(&format!("{json:?},\n"));
        }
        source.push_str("];\n");
        files.insert(
            PathBuf::from("crates/tsr_diagnostics/src/locales_generated.rs"),
            source,
        );
    }
    Ok(files)
}

fn valid_identifier(name: &str) -> bool {
    let mut bytes = name.bytes();
    bytes.next().is_some_and(|first| first.is_ascii_uppercase())
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}

fn number(value: i32) -> String {
    let digits = value.unsigned_abs().to_string();
    let mut literal = String::new();
    if value < 0 {
        literal.push('-');
    }
    for (index, digit) in digits.chars().enumerate() {
        if index != 0 && (digits.len() - index).is_multiple_of(3) {
            literal.push('_');
        }
        literal.push(digit);
    }
    literal
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn message(code: i32, name: &str) -> Value {
        json!({"name": name, "key": format!("key_{code}"), "text": "A \\\"quoted\\\" message\n",
            "code": code, "category": "Error", "reportsUnnecessary": false,
            "reportsDeprecated": false, "elidedInCompatibilityPyramid": false})
    }

    #[test]
    fn localized_exports_require_the_complete_pinned_roster() {
        let tags = [
            "zh-CN", "zh-TW", "cs-CZ", "de-DE", "es-ES", "fr-FR", "it-IT", "ja-JP", "ko-KR",
            "pl-PL", "pt-BR", "ru-RU", "tr-TR",
        ];
        let locales: serde_json::Map<_, _> = tags
            .into_iter()
            .map(|tag| (tag.to_owned(), json!({"key_1":"translated"})))
            .collect();
        let mut input = json!({"version":1,"messages":[message(1,"A")], "locales":locales});
        let files = emit(&input, "pin").unwrap();
        assert!(
            files[&PathBuf::from("crates/tsr_diagnostics/src/locales_generated.rs")]
                .contains("translated")
        );
        input["locales"]["ja-JP"] = json!({});
        assert!(emit(&input, "pin")
            .unwrap_err()
            .contains("empty localization table"));
        input["locales"].as_object_mut().unwrap().remove("ja-JP");
        assert!(emit(&input, "pin").unwrap_err().contains("roster differs"));
        input["locales"]["xx-XX"] = json!({"key_1":"translated"});
        assert!(emit(&input, "pin").unwrap_err().contains("roster differs"));
    }

    #[test]
    fn rejects_ambiguous_names_keys_and_codes() {
        for messages in [
            vec![message(2, "A"), message(1, "B")],
            vec![message(1, "A"), message(1, "B")],
            vec![message(1, "A"), message(2, "A")],
            vec![message(1, "bad identifier")],
        ] {
            assert!(emit(&json!({"version":1,"messages":messages}), "pin").is_err());
        }
        let mut second = message(2, "B");
        second["key"] = json!("key_1");
        assert!(emit(
            &json!({"version":1,"messages":[message(1,"A"),second]}),
            "pin"
        )
        .is_err());
    }

    #[test]
    fn rejects_unknown_categories_and_incomplete_exports() {
        let mut item = message(1, "A");
        item["category"] = json!("FutureCategory");
        assert!(emit(&json!({"version":1,"messages":[item]}), "pin").is_err());
        assert!(emit(&json!({"version":1,"messages":[]}), "pin").is_err());
        assert!(emit(&json!({"version":2,"messages":[message(1,"A")]}), "pin").is_err());
    }
}
